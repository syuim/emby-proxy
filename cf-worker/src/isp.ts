// asn 未命中时的组织名二次兜底：只放强关键字，避免海外撞名（裸 UNICOM/NETCOM/CMCC 不用）
const CT_ORG_RE = /CHINANET|CHINATELECOM|CHINA\s+TELECOM/i;
const CU_ORG_RE = /CHINA169|CHINA\s+UNICOM|CNCGROUP|CUII/i;
const CM_ORG_RE = /CHINAMOBILE|CMNET|CMCC|CHINA\s+MOBILE|CTTNET|TIETONG|TIE\s+TONG/i;

export function classifyIsp(
  asn?: number | null,
  asOrganization?: string | null,
): IspClass {
  if (asn) {
    if (CT_ASNS.has(asn)) return "ct";
    if (CU_ASNS.has(asn)) return "cu";
    if (CM_ASNS.has(asn)) return "cm";
  }
  const org = asOrganization ?? "";
  if (CT_ORG_RE.test(org)) return "ct";
  if (CU_ORG_RE.test(org)) return "cu";
  if (CM_ORG_RE.test(org)) return "cm";
  return "unknown";
}
